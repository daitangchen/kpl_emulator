function toPlayer(a) {
  const [id, name, realName, role, teamId, age, laning, macro, teamfight, champPool, potential, value, wage, tags] = a;
  const w = ROLE_WEIGHTS[role];
  const overall = Math.round(
    laning * w.laning + macro * w.macro + teamfight * w.teamfight + champPool * w.champPool,
  );
  return {
    id, name, realName, role, teamId, age,
    laning, macro, teamfight, champPool,
    overall, potential, value, wage, tags: tags || [],
  };
}

export const PLAYERS = RAW.map(toPlayer);
export const PLAYER_BY_ID = Object.fromEntries(PLAYERS.map((p) => [p.id, p]));

/** 战队名册：[首发5人, 替补, 青训] */
export function squadOf(teamId) {
  // 容错：传进来的是战队对象而不是 id 时，自动取 id，避免静默返回空名册
  const id = (teamId && typeof teamId === 'object') ? teamId.id : teamId;
  const list = PLAYERS.filter((p) => p.teamId === id);
  if (!list.length) {
    console.warn(`[squadOf] 战队 "${id}" 没有任何球员，检查传入的是不是战队 id 字符串`);
  }
  const byRole = (r) => list.filter((p) => p.role === r).sort((a, b) => b.overall - a.overall);
  const starters = ROLE_ORDER.map((r) => byRole(r)[0]).filter(Boolean);
  const starterIds = new Set(starters.map((p) => p.id));
  const rest = list.filter((p) => !starterIds.has(p.id));
  return {
    starters,
    bench: rest.filter((p) => !p.tags.includes('青训')),
    youth: rest.filter((p) => p.tags.includes('青训')),
    all: list,
  };
}

/** 战队战力：首发五人综合 + 位置均衡度 */
export function teamPowerFromSquad(teamId) {
  const { starters } = squadOf(teamId);
  if (!starters.length) return 50;
  const avg = starters.reduce((s, p) => s + p.overall, 0) / starters.length;
  const missing = 5 - starters.length;
  return Math.max(20, avg - missing * 6);
}
